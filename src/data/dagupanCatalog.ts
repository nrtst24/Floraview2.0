export function getTotalStemCount(stems: Record<FlowerSpeciesId, number>): number {
  return Object.values(stems).reduce((acc, count) => acc + Math.max(0, count), 0);
}

export function calculateBouquetPrice(config: BouquetConfig): number {
  const stemsCost = FLOWER_SPECIES.reduce((sum, sp) => {
    const qty = Math.max(0, config.stems[sp.id] || 0);
    return sum + qty * sp.unitPrice;
  }, 0);
  const wrap = WRAP_STYLES.find((w) => w.id === config.wrapStyle) || WRAP_STYLES[0];
  return stemsCost + wrap.price;
}

